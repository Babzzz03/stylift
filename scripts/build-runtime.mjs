// The trigger script that exports carry (scroll-into-view entrances, the site's widgets, pointer effects…), built
// READABLE — real names, indented, a header saying what it does — so whoever opens an export can follow it:
//   • public/sl-motion-runtime.js — Studio's Preview (a page at an extension-internal address may only run scripts
//     from the extension's own files; inline ones are blocked there) loads it from this file;
//   • src/studio/motion-runtime.generated.ts — the same text, which exports inline (the extension's own bundle is
//     minified: its copy of the function would be unreadable).
import { buildSync } from "esbuild";
import { writeFileSync } from "node:fs";
const r = buildSync({ entryPoints: ["src/studio/motion.ts"], bundle: true, format: "cjs", platform: "neutral", write: false, minify: false, keepNames: false });
const m = { exports: {} };
new Function("module", "exports", r.outputFiles[0].text)(m, m.exports);
const HEADER = `/*
 * StyleLift — the page's motion, replayed (generated with this export; no dependencies).
 *  • Entrances that wait until they are scrolled into view ([data-sl-in-on="enter"], Studio "Scroll into view")
 *    are held at their first frame and played as they come in; word-by-word texts are split into words.
 *  • The site's own one-shot CSS animations further down ([data-sl-hold]) wait the same way.
 *  • Widgets the site's scripts ran: tabs ([data-sl-tabs]), gallery arrows ([data-sl-paddle] + [data-sl-scroller]),
 *    video buttons ([data-sl-media]) and the playing / paused / ended classes the site's CSS reads.
 *  • Classes the page put on itself past a scroll position ([data-sl-scroll-classes]).
 *  • Pointer effects (magnetic, 3D tilt, cursor followers) and videos played once as they come into view.
 * Remove this script and everything simply shows in its final state.
 */`;
const src = m.exports.motionRuntimeSource();
writeFileSync("public/sl-motion-runtime.js", `${HEADER}\n${src}\n`);
writeFileSync("src/studio/motion-runtime.generated.ts", `// Generated by scripts/build-runtime.mjs from motion.ts — do not edit.\n// The readable trigger script exports carry (see motionRuntimeSource).\nexport const READABLE_RUNTIME = ${JSON.stringify(`${HEADER}\n${src}`)};\n`);
console.log(`motion runtime → public/sl-motion-runtime.js, src/studio/motion-runtime.generated.ts (${src.length} chars, readable)`);
